async def seed_golden_dataset(session: AsyncSession) -> int:
    """Inserts golden reference samples if the table is empty or upon request."""
    stmt = select(GoldenSample)
    existing = (await session.execute(stmt)).scalars().all()
    if existing:
        return len(existing)

    count = 0
    for seed in GOLDEN_SEEDS:
        # Generate embedding if possible
        full_text = f"{seed['title']} {seed['text']}"
        embedding_vec = await get_embedding(full_text)
        
        sample = GoldenSample(
            title=seed["title"],
            text=seed["text"],
            sufficiency_score=seed["sufficiency_score"],
            discipline_score=seed["discipline_score"],
            integrity_score=seed["integrity_score"],
            public_mind_score=seed["public_mind_score"],
            gratitude_score=seed["gratitude_score"],
            evidence_quote=seed["evidence_quote"],
            rationale=seed["rationale"],
            province=seed["province"],
            category=seed["category"],
            embedding=embedding_vec,
            created_by="Expert Panel (Moral Center Rubric)"
        )
        session.add(sample)
        count += 1

    await session.commit()
    print(f"[SocialEye] Seeded {count} Golden Samples into the database.")
    return count
