# Short names / common aliases
ALIASES = {
    "กทม": "กรุงเทพมหานคร",
    "กทม.": "กรุงเทพมหานคร",
    "กรุงเทพ": "กรุงเทพมหานคร",
    "โคราช": "นครราชสีมา",
    "อยุธยา": "พระนครศรีอยุธยา",
    "แปดริ้ว": "ฉะเชิงเทรา",
    "ปากน้ำ": "สมุทรปราการ"
}

def extract_province(text: str) -> str:
    """Finds the most specific Thai province mentioned in text, or returns 'ระดับประเทศ'."""
    if not text:
        return "ระดับประเทศ"
        
    for alias, standard_name in ALIASES.items():
        if re.search(r'\b' + re.escape(alias) + r'\b|จ\.' + re.escape(alias) + r'|จังหวัด' + re.escape(alias), text):
            return standard_name

    for province in THAI_PROVINCES:
        # Match 'จ.ขอนแก่น', 'จังหวัดขอนแก่น', or standalone province name
        pattern = r'(จังหวัด|จ\.)?' + re.escape(province)
        if re.search(pattern, text):
            return province

    return "ระดับประเทศ"
